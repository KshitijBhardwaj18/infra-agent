"use client";

import { useEffect, useState, useCallback } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";
import { Copy, Check, ExternalLink } from "lucide-react";
import type { HeizenConfig } from "@heizen/shared";
import { ConnectGitHub } from "@/components/github/ConnectGitHub";
import { IndexingProgress } from "@/components/github/IndexingProgress";
import { IndexingResults } from "@/components/indexing/IndexingResults";
import { DeployForm } from "@/components/deploy/DeployForm";
import { DeployingState } from "@/components/deploy/DeployingState";
import { CostEstimator } from "@/components/deploy/CostEstimator";
import { ResourceGraph } from "@/components/resources/ResourceGraph";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import { api } from "@/lib/api";
import { useSse } from "@/hooks/useSse";
import { useIndexingComplete, useEnvironmentStatus } from "@/hooks/useWebSocket";
import type { IndexingSsePayload } from "@heizen/shared";

interface Project {
  id: string;
  slug: string;
  githubOwner: string | null;
  githubRepo: string | null;
  githubInstallationId: string | null;
}

interface Environment {
  id: string;
  type: string;
  status: string;
  heizenConfig: HeizenConfig | null;
  lastDeployedAt: string | null;
  stackOutputs: Record<string, unknown> | null;
}

interface EnvVar {
  hasValue: boolean;
  isAutoGenerated: boolean;
}

function CopyButton({ value }: { value: string }) {
  const [copied, setCopied] = useState(false);

  const copy = async () => {
    await navigator.clipboard.writeText(value);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <Button variant="ghost" size="icon-sm" onClick={copy} className="shrink-0">
      {copied ? <Check size={14} className="text-green-500" /> : <Copy size={14} />}
    </Button>
  );
}

export default function EnvironmentPage({
  params,
}: {
  params: Promise<{ projectSlug: string; env: string }>;
}) {
  const router = useRouter();
  const [projectSlug, setProjectSlug] = useState("");
  const [envType, setEnvType] = useState<"staging" | "production">("staging");
  const [project, setProject] = useState<Project | null>(null);
  const [environment, setEnvironment] = useState<Environment | null>(null);
  const [indexing, setIndexing] = useState(false);
  const [showDeployForm, setShowDeployForm] = useState(false);
  const [resources, setResources] = useState<
    Array<{ id: string; pulumiUrn: string; type: string; name: string; dependencies: string[] }>
  >([]);
  const [missingEnvCount, setMissingEnvCount] = useState(0);
  const [loading, setLoading] = useState(true);

  const indexStreamUrl = project
    ? `/api/projects/${project.id}/github/index/stream`
    : null;
  const { data: indexEvents, reset: resetIndexEvents } = useSse<IndexingSsePayload>(
    indexStreamUrl,
    indexing,
  );

  const load = useCallback(async (slug: string, env: string) => {
    const projects = await api<Array<Project & { environments: Environment[] }>>("/api/projects");
    const p = projects.find((pr) => pr.slug === slug);
    if (!p) return;

    setProject(p);
    const envRecord = p.environments.find(
      (e) => e.type.toLowerCase() === env.toLowerCase(),
    );
    if (envRecord) {
      setEnvironment(envRecord);
      if (envRecord.status === "LIVE") {
        const res = await api<typeof resources>(
          `/api/projects/${p.id}/environments/${envRecord.id}/resources`,
        );
        setResources(res);
      }
      const vars = await api<EnvVar[]>(
        `/api/projects/${p.id}/environments/${envRecord.id}/env-vars`,
      );
      setMissingEnvCount(vars.filter((v) => !v.hasValue && !v.isAutoGenerated).length);
    }
    setLoading(false);
  }, []);

  useEffect(() => {
    params.then(({ projectSlug: slug, env }) => {
      setProjectSlug(slug);
      setEnvType(env as "staging" | "production");
      load(slug, env);
    });
  }, [params, load]);

  useIndexingComplete((payload) => {
    if (payload.projectId === project?.id) {
      setIndexing(false);
      load(projectSlug, envType);
    }
  });

  useEnvironmentStatus((payload) => {
    if (payload.environmentId === environment?.id) {
      setEnvironment((e) => (e ? { ...e, status: payload.status } : e));
      if (payload.status === "LIVE" && project && environment) {
        load(projectSlug, envType);
      }
    }
  });

  const handleDeploy = (deploymentId: string) => {
    setShowDeployForm(false);
    if (project && environment) {
      router.push(
        `/projects/${projectSlug}/${envType}/deployments/${deploymentId}`,
      );
    }
  };

  const startIndexing = async () => {
    if (!project || !environment) return;
    setIndexing(true);
    resetIndexEvents();
    await api(`/api/projects/${project.id}/github/index`, {
      method: "POST",
      body: JSON.stringify({ environmentId: environment.id }),
    });
  };

  if (loading || !project || !environment) {
    return (
      <div className="space-y-4">
        <Skeleton className="h-8 w-48" />
        <Skeleton className="h-32 w-full rounded-lg" />
        <Skeleton className="h-64 w-full rounded-lg" />
      </div>
    );
  }

  if (!project.githubOwner || !project.githubInstallationId) {
    return <ConnectGitHub projectId={project.id} />;
  }

  if (indexing) {
    return <IndexingProgress events={indexEvents} />;
  }

  if (environment.status === "DEPLOYING") {
    return (
      <DeployingState
        projectId={project.id}
        projectSlug={projectSlug}
        envType={envType}
        environmentId={environment.id}
      />
    );
  }

  if (environment.status === "LIVE" && environment.heizenConfig) {
    const outputs = environment.stackOutputs as Record<string, string> | null;
    const appUrl = outputs?.albDnsName ? `https://${outputs.albDnsName}` : null;

    return (
      <div className="space-y-6">
        <div className="flex items-center justify-between rounded-lg border border-zinc-800 bg-zinc-900 p-4">
          <div className="flex items-center gap-3">
            <span className="h-2 w-2 animate-pulse rounded-full bg-green-500" />
            <span className="text-sm font-medium">Live</span>
            {environment.lastDeployedAt && (
              <span className="text-sm text-muted-foreground">
                · Last deployed {new Date(environment.lastDeployedAt).toLocaleString()}
              </span>
            )}
          </div>
          <Button size="sm" onClick={() => setShowDeployForm(true)}>
            Redeploy
          </Button>
        </div>

        <div className="grid gap-3 lg:grid-cols-2">
          <div className="rounded-lg border border-zinc-800 bg-zinc-900 p-4">
            <p className="text-sm font-medium uppercase tracking-wide text-muted-foreground">
              Endpoints
            </p>
            {appUrl ? (
              <div className="mt-3 space-y-2">
                <div className="flex items-center gap-2 rounded-md border border-zinc-800 bg-zinc-950 px-3 py-2">
                  <a
                    href={appUrl}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="flex-1 truncate text-sm text-blue-400 hover:underline"
                  >
                    {outputs?.albDnsName}
                  </a>
                  <CopyButton value={appUrl} />
                  <a href={appUrl} target="_blank" rel="noopener noreferrer">
                    <Button variant="ghost" size="icon-sm">
                      <ExternalLink size={14} />
                    </Button>
                  </a>
                </div>
              </div>
            ) : (
              <p className="mt-3 text-sm text-muted-foreground">No endpoints available yet.</p>
            )}
          </div>

          <div className="rounded-lg border border-zinc-800 bg-zinc-900 p-4">
            <p className="text-sm font-medium uppercase tracking-wide text-muted-foreground">
              DNS Configuration
            </p>
            {environment.heizenConfig.domain && outputs?.albDnsName ? (
              <div className="mt-3 space-y-3">
                <div className="rounded-md border border-zinc-800 bg-zinc-950 p-3 text-sm">
                  <div className="flex items-center justify-between gap-2">
                    <span className="text-muted-foreground">Type</span>
                    <Badge variant="outline">CNAME</Badge>
                  </div>
                  <div className="mt-2 flex items-center justify-between gap-2">
                    <span className="text-muted-foreground">Name</span>
                    <span className="font-mono text-xs">{environment.heizenConfig.domain}</span>
                  </div>
                  <div className="mt-2 flex items-center justify-between gap-2">
                    <span className="text-muted-foreground">Value</span>
                    <div className="flex items-center gap-1">
                      <span className="font-mono text-xs">{outputs.albDnsName}</span>
                      <CopyButton value={outputs.albDnsName} />
                    </div>
                  </div>
                </div>
              </div>
            ) : (
              <p className="mt-3 text-sm text-muted-foreground">
                No custom domain configured.
              </p>
            )}
          </div>
        </div>

        <div>
          <p className="mb-3 text-sm font-medium uppercase tracking-wide text-muted-foreground">
            Infrastructure
          </p>
          <ResourceGraph resources={resources} />
        </div>

        <Link href={`/projects/${projectSlug}/${envType}/env-vars`}>
          <Button variant="outline" size="sm">
            Manage environment variables
          </Button>
        </Link>

        {showDeployForm && (
          <DeployForm
            projectId={project.id}
            environmentId={environment.id}
            envType={envType}
            initialConfig={environment.heizenConfig}
            onDeploy={handleDeploy}
            onClose={() => setShowDeployForm(false)}
          />
        )}
      </div>
    );
  }

  if (environment.heizenConfig) {
    return (
      <div>
        <div className="grid gap-3 lg:grid-cols-3">
          <div className="lg:col-span-2">
            <IndexingResults
              config={environment.heizenConfig}
              missingEnvCount={missingEnvCount}
            />
          </div>
          <div className="rounded-lg border border-zinc-800 bg-zinc-900 p-4">
            <p className="text-sm font-medium uppercase tracking-wide text-muted-foreground">
              Summary
            </p>
            <div className="mt-3">
              <CostEstimator config={environment.heizenConfig} />
            </div>
            <Button
              size="sm"
              className="mt-4 w-full"
              onClick={() => setShowDeployForm(true)}
            >
              Configure &amp; Deploy
            </Button>
            <Button
              variant="outline"
              size="sm"
              className="mt-2 w-full"
              onClick={startIndexing}
            >
              Re-index
            </Button>
          </div>
        </div>

        {showDeployForm && (
          <DeployForm
            projectId={project.id}
            environmentId={environment.id}
            envType={envType}
            initialConfig={environment.heizenConfig}
            onDeploy={handleDeploy}
            onClose={() => setShowDeployForm(false)}
          />
        )}
      </div>
    );
  }

  return (
    <div className="flex min-h-[400px] flex-col items-center justify-center text-center">
      <p className="text-sm text-muted-foreground">Repository connected. Ready to analyze.</p>
      <Button size="sm" className="mt-4" onClick={startIndexing}>
        Analyze codebase
      </Button>
    </div>
  );
}
