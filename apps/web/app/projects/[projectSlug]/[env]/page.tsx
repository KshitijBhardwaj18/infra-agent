"use client";

import { useEffect, useState, useCallback } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";
import type { HeizenConfig } from "@heizen/shared";
import { ConnectGitHub } from "@/components/github/ConnectGitHub";
import { IndexingProgress } from "@/components/github/IndexingProgress";
import { IndexingResults } from "@/components/indexing/IndexingResults";
import { DeployForm } from "@/components/deploy/DeployForm";
import { DeployingState } from "@/components/deploy/DeployingState";
import { ResourceGraph } from "@/components/resources/ResourceGraph";
import { Button, Card, Badge } from "@/components/ui";
import { api } from "@/lib/api";
import { useSse } from "@/hooks/useSse";
import { useIndexingComplete, useEnvironmentStatus } from "@/hooks/useWebSocket";
import type { IndexingSsePayload } from "@heizen/shared";

interface Project {
  id: string;
  slug: string;
  githubOwner: string | null;
  githubRepo: string | null;
  githubInstallationId: string | null;
}

interface Environment {
  id: string;
  type: string;
  status: string;
  heizenConfig: HeizenConfig | null;
  lastDeployedAt: string | null;
  stackOutputs: Record<string, unknown> | null;
}

interface EnvVar {
  hasValue: boolean;
  isAutoGenerated: boolean;
}

export default function EnvironmentPage({
  params,
}: {
  params: Promise<{ projectSlug: string; env: string }>;
}) {
  const router = useRouter();
  const [projectSlug, setProjectSlug] = useState("");
  const [envType, setEnvType] = useState<"staging" | "production">("staging");
  const [project, setProject] = useState<Project | null>(null);
  const [environment, setEnvironment] = useState<Environment | null>(null);
  const [indexing, setIndexing] = useState(false);
  const [showDeployForm, setShowDeployForm] = useState(false);
  const [resources, setResources] = useState<Array<{ id: string; pulumiUrn: string; type: string; name: string; dependencies: string[] }>>([]);
  const [missingEnvCount, setMissingEnvCount] = useState(0);

  const indexStreamUrl = project
    ? `/api/projects/${project.id}/github/index/stream`
    : null;
  const { data: indexEvents, reset: resetIndexEvents } = useSse<IndexingSsePayload>(
    indexStreamUrl,
    indexing,
  );

  const load = useCallback(async (slug: string, env: string) => {
    const projects = await api<Array<Project & { environments: Environment[] }>>("/api/projects");
    const p = projects.find((pr) => pr.slug === slug);
    if (!p) return;

    setProject(p);
    const envRecord = p.environments.find(
      (e) => e.type.toLowerCase() === env.toLowerCase(),
    );
    if (envRecord) {
      setEnvironment(envRecord);
      if (envRecord.status === "LIVE") {
        const res = await api<typeof resources>(
          `/api/projects/${p.id}/environments/${envRecord.id}/resources`,
        );
        setResources(res);
      }
      const vars = await api<EnvVar[]>(
        `/api/projects/${p.id}/environments/${envRecord.id}/env-vars`,
      );
      setMissingEnvCount(vars.filter((v) => !v.hasValue && !v.isAutoGenerated).length);
    }
  }, []);

  useEffect(() => {
    params.then(({ projectSlug: slug, env }) => {
      setProjectSlug(slug);
      setEnvType(env as "staging" | "production");
      load(slug, env);
    });
  }, [params, load]);

  useIndexingComplete((payload) => {
    if (payload.projectId === project?.id) {
      setIndexing(false);
      load(projectSlug, envType);
    }
  });

  useEnvironmentStatus((payload) => {
    if (payload.environmentId === environment?.id) {
      setEnvironment((e) => (e ? { ...e, status: payload.status } : e));
      if (payload.status === "LIVE" && project && environment) {
        load(projectSlug, envType);
      }
    }
  });

  const handleDeploy = (deploymentId: string) => {
    setShowDeployForm(false);
    if (project && environment) {
      router.push(
        `/projects/${projectSlug}/${envType}/deployments/${deploymentId}`,
      );
    }
  };

  if (!project || !environment) {
    return <p className="text-[var(--muted)]">Loading...</p>;
  }

  // State 1: GitHub not connected
  if (!project.githubOwner || !project.githubInstallationId) {
    return <ConnectGitHub projectId={project.id} />;
  }

  // State 2: Indexing running
  if (indexing) {
    return <IndexingProgress events={indexEvents} />;
  }

  // Deployment in progress
  if (environment.status === "DEPLOYING") {
    return (
      <DeployingState
        projectId={project.id}
        projectSlug={projectSlug}
        envType={envType}
        environmentId={environment.id}
      />
    );
  }

  // State 4: Deployed / LIVE
  if (environment.status === "LIVE" && environment.heizenConfig) {
    const outputs = environment.stackOutputs as Record<string, string> | null;
    return (
      <div className="space-y-6">
        <div className="flex items-center justify-between">
          <div>
            <h1 className="text-2xl font-bold capitalize">{envType}</h1>
            <Badge variant="success">Live</Badge>
          </div>
          <Button onClick={() => setShowDeployForm(true)}>Redeploy</Button>
        </div>

        {outputs?.albDnsName && (
          <Card>
            <h2 className="mb-2 font-semibold">Application URL</h2>
            <a
              href={`https://${outputs.albDnsName}`}
              target="_blank"
              rel="noopener noreferrer"
              className="text-[var(--accent)] hover:underline"
            >
              {outputs.albDnsName}
            </a>
            {environment.heizenConfig.domain && (
              <p className="mt-2 text-sm text-[var(--muted)]">
                Configure DNS: CNAME {environment.heizenConfig.domain} → {outputs.albDnsName}
              </p>
            )}
          </Card>
        )}

        {environment.lastDeployedAt && (
          <p className="text-sm text-[var(--muted)]">
            Last deployed: {new Date(environment.lastDeployedAt).toLocaleString()}
          </p>
        )}

        <div>
          <h2 className="mb-4 text-lg font-semibold">Resource Graph</h2>
          <ResourceGraph resources={resources} />
        </div>

        <Link href={`/projects/${projectSlug}/${envType}/env-vars`}>
          <Button variant="outline">Manage Environment Variables</Button>
        </Link>

        {showDeployForm && (
          <DeployForm
            projectId={project.id}
            environmentId={environment.id}
            envType={envType}
            initialConfig={environment.heizenConfig}
            onDeploy={handleDeploy}
            onClose={() => setShowDeployForm(false)}
          />
        )}
      </div>
    );
  }

  // State 3: Indexed, not deployed
  if (environment.heizenConfig) {
    return (
      <div>
        <h1 className="mb-6 text-2xl font-bold capitalize">{envType}</h1>
        <IndexingResults
          config={environment.heizenConfig}
          missingEnvCount={missingEnvCount}
          onConfigure={() => setShowDeployForm(true)}
        />
        <div className="mt-4 flex gap-2">
          <Button
            variant="outline"
            onClick={async () => {
              setIndexing(true);
              resetIndexEvents();
              await api(`/api/projects/${project.id}/github/index`, {
                method: "POST",
                body: JSON.stringify({ environmentId: environment.id }),
              });
            }}
          >
            Re-index
          </Button>
        </div>
        {showDeployForm && (
          <DeployForm
            projectId={project.id}
            environmentId={environment.id}
            envType={envType}
            initialConfig={environment.heizenConfig}
            onDeploy={handleDeploy}
            onClose={() => setShowDeployForm(false)}
          />
        )}
      </div>
    );
  }

  // Connected but not indexed — trigger indexing
  return (
    <div className="text-center space-y-4">
      <p className="text-[var(--muted)]">Repository connected. Ready to analyze.</p>
      <Button
        onClick={async () => {
          setIndexing(true);
          resetIndexEvents();
          await api(`/api/projects/${project.id}/github/index`, {
            method: "POST",
            body: JSON.stringify({ environmentId: environment.id }),
          });
        }}
      >
        Analyze Codebase
      </Button>
      {indexing && <IndexingProgress events={indexEvents} />}
    </div>
  );
}
